#!/usr/bin/env python3
"""Turn chosen tracks of a MIDI file into a JS note-data module.

    python3 tools/extract_midi.py FILE.mid EXPORT_NAME TRACK [TRACK ...] > js/music/x.data.js

Each track becomes one "beat:dur:midi ..." string (quarter note = 1 beat,
snapped to a 16th-note grid). Decode with notation.js decode().
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from midi import parse

path, name, *tracks = sys.argv[1:]
div, trs = parse(path)
print('// GENERATED by tools/extract_midi.py from %s. Do not hand-edit.' % os.path.basename(path))
print('export const %s = [' % name)
for t in map(int, tracks):
    ns = sorted((round(s / div * 4) / 4, max(0.25, round((e - s) / div * 4) / 4), n)
                for n, s, e in (x for x in trs[t][1] if x[0] != 'TS'))
    print('  %r,' % ' '.join('%g:%g:%d' % x for x in ns))
print('];')
