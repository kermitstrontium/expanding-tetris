#!/usr/bin/env python3
"""Regenerate js/music/bach.js from the Mutopia Project MIDI files.

Only pitches and timings are taken: the notes are Bach's (public domain).
The chiptune arrangement (voices, waveforms, tempo, octave choices) lives in
js/music/bach.js and the audio engine.

    curl -LO https://www.mutopiaproject.org/ftp/BachJS/BWV814/french-suite-3/french-suite-3-mids.zip
    python3 tools/extract_bach.py french-suite-3-mids.zip > js/music/bach.js
"""
import io, os, sys, zipfile, tempfile
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from midi import parse


def voices(z, name):
    with tempfile.NamedTemporaryFile(suffix='.mid') as f:
        f.write(z.read(name)); f.flush()
        div, tracks = parse(f.name)
    out = []
    for _, notes in tracks:
        ns = sorted((round(s / div * 4) / 4, round((e - s) / div * 4) / 4, n)
                    for n, s, e in (x for x in notes if x[0] != 'TS'))
        if ns:
            out.append(ns)
    return out


def enc(ns):
    # "beat:dur:midi" triples, beats in quarter notes
    return ' '.join('%g:%g:%d' % t for t in ns)


z = zipfile.ZipFile(sys.argv[1])
mv = {m: voices(z, 'bach-french-suite-3-%s.mid' % m) for m in ('menuet', 'trio', 'gavotte')}
print('// GENERATED by tools/extract_bach.py. Do not hand-edit.')
print('// J. S. Bach, French Suite No. 3 in B minor, BWV 814 (public domain).')
print('// Note data from the Mutopia Project MIDI. Arrangement is ours.')
print('export const BACH = {')
for k, vs in mv.items():
    print('  %s: [' % k)
    for v in vs:
        print('    %r,' % enc(v))
    print('  ],')
print('};')
